export class DoctorAiAssistant implements OnInit {
  queryText = '';

  presetQueries = [
    'Summarize Rahul Kumar Patel\'s cardiac history.',
    'Check drug conflicts for Amlodipine & Penicillin on record P1001.',
    'Search for patients currently admitted in ICU.',
    'Show patients with abnormal HbA1c results last month.'
  ];

  chatMessages = signal<Message[]>([]);
  private readonly http = inject(HttpClient);
  private readonly authService = inject(AuthService);
  private loadingResponse = signal(false);

  ngOnInit() {
    this.chatMessages.set([
      {
        role: 'assistant',
        text: 'Hello. I am your clinical AI assistant. Ask me questions about patient records, and I will query the hospital database for real data.',
      }
    ]);
  }

  async sendQuery() {
    const query = this.queryText.trim();
    if (!query) return;

    this.chatMessages.update(msgs => [...msgs, { role: 'user', text: query }]);
    this.queryText = '';
    this.loadingResponse.set(true);

    try {
      const user = this.authService.currentUser();
      const body: any = { message: query };
      if (user?.uhid) {
        body.patientUhid = user.uhid;
      }

      const response = await firstValueFrom(this.http.post(`${getApiBaseUrl()}/ai/chat`, body)) as any;
      if (response.success && response.data) {
        this.chatMessages.update(msgs => [
          ...msgs,
          {
            role: 'assistant',
            text: response.data.response,
            sources: response.data.sources,
            confidence: response.data.confidence ? (response.data.confidence > 0.8 ? 'High' : response.data.confidence > 0.5 ? 'Medium' : 'Low') : 'Medium'
          }
        ]);
      } else {
        this.chatMessages.update(msgs => [
          ...msgs,
          { role: 'assistant', text: response.message || 'Unable to process query.', sources: [], confidence: 'Low' }
        ]);
      }
    } catch {
      this.chatMessages.update(msgs => [
        ...msgs,
        { role: 'assistant', text: 'Error connecting to AI service. Please try again.', sources: [], confidence: 'Low' }
      ]);
    } finally {
      this.loadingResponse.set(false);
    }
  }

  async runPreset(query: string) {
    this.chatMessages.update(msgs => [...msgs, { role: 'user', text: query }]);
    this.loadingResponse.set(true);

    try {
      const user = this.authService.currentUser();
      const body: any = { message: query };
      if (user?.uhid) {
        body.patientUhid = user.uhid;
      }

      const response = await firstValueFrom(this.http.post(`${getApiBaseUrl()}/ai/chat`, body)) as any;
      if (response.success && response.data) {
        this.chatMessages.update(msgs => [
          ...msgs,
          {
            role: 'assistant',
            text: response.data.response,
            sources: response.data.sources,
            confidence: response.data.confidence ? (response.data.confidence > 0.8 ? 'High' : response.data.confidence > 0.5 ? 'Medium' : 'Low') : 'Medium'
          }
        ]);
      } else {
        this.chatMessages.update(msgs => [
          ...msgs,
          { role: 'assistant', text: response.message || 'Unable to process query.', sources: [], confidence: 'Low' }
        ]);
      }
    } catch {
      this.chatMessages.update(msgs => [
        ...msgs,
        { role: 'assistant', text: 'Error connecting to AI service. Please try again.', sources: [], confidence: 'Low' }
      ]);
    } finally {
      this.loadingResponse.set(false);
    }
  }
}
